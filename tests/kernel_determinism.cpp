#include "native/Engine.h"
#include "ChunkCodec.h"
#include <fstream>
#include <future>
#include <iostream>
int main(int argc,char** argv) {
    try {
        if(argc!=2)throw std::runtime_error("expected generated native input");
        nativegen::J data;std::ifstream(argv[1])>>data;
        std::vector<std::pair<int,int>> coordinates{{0,0},{-1,-1},{80,80},{1000,-1000}};
        auto run=[&](bool reverse) {
            nativegen::Engine engine(data);
            std::map<std::pair<int,int>,std::vector<uint8_t>> result;
            auto order=coordinates;if(reverse)std::reverse(order.begin(),order.end());
            for(auto p:order) {
                auto bytes=engine.chunk(p.first,p.second);
                auto decoded=terrain_runtime::decodeChunk(bytes,168,25);
                for(auto offset:decoded.columns) {
                    auto const& r=decoded.runs;
                    if(r[offset+4]!=1||r[offset+5]!=0)
                        throw std::runtime_error("Generated column lost bottom bedrock");
                }
                result.emplace(p,std::move(bytes));
            }
            // Revisit after other columns have changed per-engine cache state.
            for(auto p:coordinates)if(engine.chunk(p.first,p.second)!=result.at(p))
                throw std::runtime_error("Repeated chunk differs after cache reuse");
            return result;
        };
        auto a=std::async(std::launch::async,[&]{return run(false);});
        auto b=std::async(std::launch::async,[&]{return run(true);});
        if(a.get()!=b.get())throw std::runtime_error("Worker/order changed generated bytes");
        std::cout<<"seed="<<data["seedManifest"]["terrainSeed"]
                 <<"; 4 chunks, two concurrent workers, reverse order, revisit and bedrock checked\n";
    }catch(std::exception const& e){std::cerr<<e.what()<<'\n';return 1;}
}
