set_targetdir(path.absolute(path.join(get_config("builddir") or "build", "$(plat)/$(arch)/$(mode)"), os.projectdir()))
-- A separate SDK build directory: never reconfigure the running BDS project.
add_rules("mode.debug", "mode.release")
includes("../../build-support/game-line.lua")
includes("../../build-support/structure-sdk.lua")
if get_config("game_line") ~= "26.20" then
    add_defines("SHANHAI_MC_26_51")
end
includes("../../src/kernel")
add_repositories("levimc-repo https://github.com/LiteLDev/xmake-repo.git")
add_requires("levilamina " .. (get_config("game_line") == "26.20" and "26.20.7" or "26.51.9"),
    {configs = {target_type = "client"}})
add_requires("levibuildscript")
set_runtimes("MD")
set_languages("c++20")
set_toolchains("clang-cl")

target("karma-worldgen-client")
    on_load(shanhai_structure_sdk_overlay)
    add_deps("terrain-kernel")
    set_default(false)
    set_kind("shared")
    set_symbols("debug")
    add_rules("@levibuildscript/linkrule")
    add_packages("levilamina")
    add_defines("KARMA_CLIENT", "NOMINMAX", "UNICODE")
    add_cxflags("/EHa", "/utf-8", "/fp:precise", "/clang:-ffp-contract=off", "-Wno-invalid-offsetof")
    add_includedirs("../../src")
    add_files("client.cpp", "../../src/Worldgen.cpp", "../../experiments/vanilla-structure-runtime/lab.cpp", "../../src/MemoryOperators.cpp")
    add_syslinks("bcrypt")
target_end()

