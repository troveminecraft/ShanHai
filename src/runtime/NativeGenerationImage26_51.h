inline constexpr auto const& tasks(Platform platform){return platform==Platform::Client?ClientTasks:ServerTasks;}
template<class Reader> bool inspect(Platform platform,Reader read){
 auto u16=[&](uint32_t a){uint16_t v=0;read(a,&v,2);return v;};
 auto u32=[&](uint32_t a){uint32_t v=0;read(a,&v,4);return v;};
 if(u16(0)!=0x5a4d)return false;auto nt=u32(0x3c);
 if(nt<0x40||nt>0x1000||u32(nt)!=0x4550||u16(nt+4)!=0x8664||u16(nt+24)!=0x20b)return false;
 auto size=u32(nt+24+56);
 if(platform==Platform::Client){
  if(u32(nt+8)!=ClientTimestamp||(size!=0x12c01000&&size!=0x12c0c000&&size!=0x12c0d000))return false;
 }else if(u32(nt+8)!=ServerTimestamp||size!=ServerImageSize)return false;
 // The first 32 bytes can already carry another ShanHai module's LL detour.
 // Verify the unchanged body/closure loads, so terrain and structure hooks
 // can chain at the same native entry without rejecting each other's detour.
 for(auto const& entry:tasks(platform)){
  std::array<unsigned char,64> bytes{};
  if(!read(entry.rva+32,bytes.data(),bytes.size())||bytes!=entry.body)return false;
 }
 return true;
}
