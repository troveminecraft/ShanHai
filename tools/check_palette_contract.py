"""Check the frozen numeric block/state and biome contract; --write regenerates C++."""
import argparse, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def generated(contract):
    data = json.dumps({key:contract[key] for key in ('palette','biomeNames','profiles')}, ensure_ascii=True, separators=(',',':'))
    return '''// Generated by tools/check_palette_contract.py --write. Do not hand-edit.
#pragma once
#include <nlohmann/json.hpp>
#include <stdexcept>
#include <charconv>
#include "ForestCapabilities.h"
namespace terrain_runtime {
inline nlohmann::json const& paletteContract() {
    static const auto value = nlohmann::json::parse(R"SHANHAI(''' + data + ''')SHANHAI");
    return value;
}
inline nlohmann::json contractSizes(nlohmann::json const& metadata) {
    auto p=forest_capabilities::profile(metadata);
    std::string name;
    if(p!=forest_capabilities::Profile::Legacy)name=metadata.at("capabilityProfile");
    else {
        auto version=metadata.value("version",std::string{});
        if(version.empty())return {{"palette",paletteContract().at("palette").size()},{"biomeNames",paletteContract().at("biomeNames").size()}};
        constexpr std::string_view prefix="karma-terrain-2.";
        if(!version.starts_with(prefix))throw std::runtime_error("Unknown terrain contract version");
        int revision=0;auto end=version.find('.',prefix.size());
        if(end==std::string::npos)throw std::runtime_error("Malformed terrain contract version");
        auto parsed=std::from_chars(version.data()+prefix.size(),version.data()+end,revision);
        if(parsed.ec!=std::errc{}||parsed.ptr!=version.data()+end||revision<193||revision>216)
            throw std::runtime_error("Terrain contract requires explicit target capabilities");
        name=revision<=195?"legacy":revision<=207?"completed":"elevated";
    }
    return paletteContract().at("profiles").at(name);
}
inline void validatePaletteContract(nlohmann::json const& metadata) {
    auto sizes=contractSizes(metadata);
    for (auto key : {"palette", "biomeNames"}) {
        auto const& expected = paletteContract().at(key);
        auto const& actual = metadata.at(key);
        size_t size=sizes.at(key);
        if (!actual.is_array() || actual.size() != size)
            throw std::runtime_error(std::string("Terrain contract size mismatch: ") + key);
        auto overrides=key==std::string_view("palette")?sizes.value("paletteOverrides",nlohmann::json::object()):nlohmann::json::object();
        for (size_t i = 0; i < size; ++i)
            if (actual[i] != (overrides.contains(std::to_string(i))?overrides.at(std::to_string(i)):expected[i]))
                throw std::runtime_error(std::string("Terrain contract mismatch: ") + key + "[" + std::to_string(i) + "]");
    }
}
}
'''

def check(write=False):
    contract=json.loads((ROOT/'data/palette-contract.json').read_bytes())
    template=json.loads((ROOT/'data/runtime-template.json').read_bytes())
    if contract['schema'] != 1: raise ValueError('Unsupported palette contract schema')
    for key in ('palette','biomeNames'):
        if template[key] != contract[key]: raise ValueError(f'Template differs from frozen {key} contract')
    header=ROOT/'src/PaletteContract.h'
    expected=generated(contract)
    if write: header.write_text(expected,'utf-8')
    elif header.read_text('utf-8') != expected: raise ValueError('PaletteContract.h is stale; review schema changes before regenerating')
    forest_header=ROOT/'src/native/ForestPalette.h'
    constants='// Generated by tools/check_palette_contract.py --write.\n#pragma once\nnamespace nativegen::forest_palette {\n'
    constants+=''.join(f'inline constexpr int {name}={value};\n' for name,value in contract['forestBlocks'].items())
    constants+='inline constexpr bool leaves(int id){return id==DarkLeaves||id==PaleLeaves||id==CherryLeaves||id==MangroveLeaves||(id>=RedPoplarLeaves&&id<=YellowPoplarLeaves)||(id>=CanopyDarkLeaves&&id<=CanopyCherryLeaves);}\n}\n'
    if write:forest_header.write_text(constants,'utf-8')
    elif forest_header.read_text('utf-8')!=constants:raise ValueError('ForestPalette.h is stale')
    if max(contract['forestBlocks'].values())>=256:raise ValueError('Forest palette exceeds byte-based terrain material support')
    print(f"Palette contract verified: {len(contract['palette'])} blocks/states, {len(contract['biomeNames'])} biomes")

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true')
    check(parser.parse_args().write)
